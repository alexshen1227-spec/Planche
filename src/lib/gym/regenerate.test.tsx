// @vitest-environment jsdom
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { StoreProvider } from '../store'
import { Train } from '../../views/Train'
import { GYM_EXERCISE_BY_ID } from '../../data/gym/exercises'
import { makeAthlete } from '../plan/wholeAthleteLoop'
import { dayKey } from '../time'
import { loadDraft, saveDraft, type DraftItem, type GymDraft } from './draft'
import { GYM_PLAN_REVISION } from './replan'
import type { GymSession } from './types'

// The saved Pull day an older generator built — a chin-up, two sets of rows and hammer curls — is rebuilt when the
// Gym screen opens; the history it was built from, and any workout with a logged set, stay exactly as they were.

afterEach(() => {
  cleanup()
  localStorage.clear()
  vi.unstubAllGlobals()
})

const item = (exerciseId: string, sets: number, load?: number): DraftItem => ({ exerciseId, unit: 'kg', restSec: 90,
  plan: { range: [8, 12], targetRpe: 8 }, sets: Array.from({ length: sets }, () => ({ reps: 8, ...(load ? { load } : {}), done: false })) })

function setUp(skills: number) {
  vi.stubGlobal('matchMedia', () => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() }))
  const athlete = makeAthlete({ skills: skills ? ['planche'] : [], active: 'home', birthYear: 1993, prefs: {
    goals: { skills, physique: 5, strength: 3, endurance: 0, power: 0 }, musclesPriority: ['chest', 'chest-upper', 'side-delts'],
  } })
  const place = athlete.gym!.locations[0]
  place.equipment = ['floor', 'dumbbells', 'incline-bench', 'pullup-bar']
  // Three earlier Pull days: four sets of eight strict pull-ups and three rows each, at midday so that no workout
  // runs past midnight into another calendar day whatever time the suite runs at (`npm run test:clock`).
  const history: GymSession[] = [9, 6, 3].map((daysAgo, i) => {
    const day = new Date(Date.now())
    day.setDate(day.getDate() - daysAgo)
    const at = day.setHours(12, 0, 0, 0)
    return { id: `logged-pull-${i}`, name: 'Pull', locationId: place.id, startedAt: at, endedAt: at + 3_600_000, exercises: [
      { exerciseId: 'pull-up', repRange: [8, 12], targetRpe: 8, sets: [0, 1, 2, 3].map((k) => ({ at: at + k * 60_000, reps: 8, rpe: 7 })) },
      { exerciseId: 'db-row', repRange: [8, 12], targetRpe: 8, sets: [4, 5, 6].map((k) => ({ at: at + k * 60_000, reps: 10, kg: 24, unit: 'kg' as const, rpe: 8 })) },
    ] }
  })
  athlete.gym!.sessions = history
  localStorage.setItem('planchelab.v1', JSON.stringify(athlete))
  localStorage.setItem('planchelab.trainMode', 'gym')
  localStorage.setItem('planchelab.todayChoice', JSON.stringify({ day: dayKey(Date.now()), kind: 'gym', gymFocus: 'pull', minutes: 28, placeId: place.id }))
  const old: GymDraft = { id: 'old-pull', planRevision: 1, name: 'Pull', startedAt: Date.now() - 600_000, locationId: place.id,
    items: [item('chin-up', 3), item('db-row', 2, 20), item('hammer-curl', 3, 10)] }
  return { place, history: JSON.parse(JSON.stringify(history)) as GymSession[], old }
}
const storedHistory = () => JSON.parse(localStorage.getItem('planchelab.v1')!).gym.sessions as GymSession[]

it.each([0, 3])('rebuilds a not-started Pull plan from an older generator as the Gym screen opens (skills goal %i)', (skills) => {
  const { history, old } = setUp(skills)
  saveDraft(old)
  render(<StoreProvider><Train startWorkout={vi.fn()} /></StoreProvider>)
  const fresh = loadDraft()!
  expect(fresh).toMatchObject({ id: 'old-pull', name: 'Pull', planRevision: GYM_PLAN_REVISION })
  const lifts = fresh.items.map((it) => [it.exerciseId, it.sets.length])
  expect(lifts).toEqual([['pull-up', 4], [expect.any(String), 4]])
  expect(GYM_EXERCISE_BY_ID[fresh.items[1].exerciseId].pattern).toBe('horizontal-pull')
  expect(fresh.items.some((it) => it.exerciseId === 'chin-up' || it.exerciseId === 'hammer-curl')).toBe(false)
  expect(storedHistory()).toEqual(history)
  // The open card lists the new plan, and the plan can be regenerated by hand at any time.
  expect(screen.getAllByText(/^Pull-up — 0 of 4 sets done$/).length).toBeGreaterThan(0)
  fireEvent.click(screen.getByRole('button', { name: /Regenerate today’s plan/ }))
  expect(loadDraft()!.items.map((it) => [it.exerciseId, it.sets.length])).toEqual(lifts)
  expect(storedHistory()).toEqual(history)
})

it('leaves a workout with a logged set exactly as it was, even when its plan is old or regenerated by hand', () => {
  const { history, old } = setUp(0)
  const started: GymDraft = { ...old, items: [{ ...old.items[0], sets: [{ reps: 8, done: true, at: Date.now() - 300_000 }, ...old.items[0].sets.slice(1)] }, ...old.items.slice(1)] }
  saveDraft(started)
  const before = localStorage.getItem('planchelab.gymDraft')
  render(<StoreProvider><Train startWorkout={vi.fn()} /></StoreProvider>)
  expect(localStorage.getItem('planchelab.gymDraft')).toBe(before)
  fireEvent.click(screen.getByRole('button', { name: /Regenerate today’s plan/ }))
  expect(localStorage.getItem('planchelab.gymDraft')).toBe(before)
  expect(storedHistory()).toEqual(history)
})

it('starts a quick log with the exercise list open', () => {
  setUp(0)
  render(<StoreProvider><Train startWorkout={vi.fn()} /></StoreProvider>)
  fireEvent.click(screen.getByRole('button', { name: /^Quick log/ }))
  fireEvent.click(screen.getByRole('button', { name: /nothing hurts.*start/i }))
  expect(loadDraft()).toMatchObject({ name: 'Quick log', items: [] })
  expect(screen.getByText(/^Quick log: choose an exercise/)).toBeTruthy()
  fireEvent.change(screen.getByRole('searchbox', { name: 'Search exercises' }), { target: { value: 'lat pullback' } })
  fireEvent.click(screen.getByRole('button', { name: /^Dumbbell lat pullback/ }))
  expect(loadDraft()!.items.map((it) => it.exerciseId)).toEqual(['db-lat-pullback'])
})
